import {chromium,expect} from '@playwright/test'
const browser=await chromium.launch({channel:'msedge',headless:true})
const page=await browser.newPage({viewport:{width:1440,height:1000}})
const errors=[];page.on('pageerror',e=>errors.push(e.message))
try{
 await page.goto('http://127.0.0.1:5180/')
 await page.getByLabel('ชื่อผู้ใช้',{exact:true}).fill('admin');await page.getByLabel('รหัสผ่าน',{exact:true}).fill('0000');await page.getByRole('button',{name:'เข้าสู่ระบบ',exact:true}).click()
 await expect(page.getByRole('heading',{name:'ภาพรวมปฏิบัติการ'})).toBeVisible()
 await page.goto('http://127.0.0.1:5180/shipments')
 const shipments=await page.evaluate(async()=>{const r=await fetch('/api/shipments',{headers:{Authorization:'Bearer '+localStorage.getItem('warehouse_token')}});return r.json()})
 await expect(page.locator('.shipment-card')).toHaveCount(shipments.length)
 const row=shipments.find(s=>s.vehicle_code&&s.delivery_run_id)||shipments[0]
 if(!row)throw Error('A read-only fixture with shipments is required')
 await page.getByLabel('กรองสถานะรายการส่ง',{exact:true}).selectOption(row.status)
 await expect(page.locator('.shipment-card')).toHaveCount(shipments.filter(s=>s.status===row.status).length)
 await page.getByLabel('กรองรถรายการส่ง',{exact:true}).selectOption(row.vehicle_code||'UNASSIGNED')
 await page.getByLabel('กรองรอบขนส่ง',{exact:true}).selectOption(row.delivery_run_id?String(row.delivery_run_id):'UNASSIGNED')
 await page.getByLabel('กรองลูกค้ารายการส่ง',{exact:true}).selectOption(row.customer_name)
 await page.getByLabel('ค้นหารายการส่ง',{exact:true}).fill(' '+row.shipment_no.toLowerCase()+' ')
 await expect(page.locator('.shipment-card')).toHaveCount(1)
 const filterUrl=page.url()
 await page.reload();await expect(page.locator('.shipment-card')).toHaveCount(1)
 await page.locator('.shipment-card').click();await expect(page).toHaveURL(new RegExp('/shipments/'+row.id+'$'))
 await page.goBack();await expect(page).toHaveURL(filterUrl);await expect(page.locator('.shipment-card')).toHaveCount(1)
 await page.getByLabel('ค้นหารายการส่ง',{exact:true}).fill('NO-SUCH-SHIPMENT-FILTER-TEST')
 await expect(page.getByText('ไม่พบรายการที่ตรงกับตัวกรอง',{exact:true})).toBeVisible()
 await page.getByRole('button',{name:'ล้างตัวกรอง',exact:true}).click()
 await expect(page.locator('.shipment-card')).toHaveCount(shipments.length)
 await page.getByLabel('กรองรถรายการส่ง',{exact:true}).selectOption('UNASSIGNED')
 await expect(page.locator('.shipment-card')).toHaveCount(shipments.filter(s=>!s.vehicle_code).length)
 await page.getByRole('button',{name:'ล้างตัวกรอง',exact:true}).click()
 await page.getByLabel('กรองสถานะรายการส่ง',{exact:true}).selectOption('ACTIVE')
 await expect(page.locator('.shipment-card')).toHaveCount(shipments.filter(s=>!['DELIVERED','RETURNED','CANCELLED'].includes(s.status)).length)
 await page.screenshot({path:'../docs/images/pro-shipment-filters.png',fullPage:true})
 await page.setViewportSize({width:390,height:844})
 await expect.poll(()=>page.locator('.pro-sidebar').evaluate(el=>Math.round(el.getBoundingClientRect().right))).toBeLessThanOrEqual(0)
 if(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth))throw Error('Mobile filters overflow')
 await page.locator('.shipment-filter-panel').screenshot({path:'../docs/images/pro-shipment-filters-mobile.png'})
 if(errors.length)throw Error(errors.join('\n'))
 console.log('PASS status, open group, vehicle, run, customer, combined search, URL persistence/reload/back, empty state, clear, unassigned vehicle and mobile; no browser errors')
}finally{await browser.close()}

