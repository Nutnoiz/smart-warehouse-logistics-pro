import {chromium,expect} from '@playwright/test'
// Every request is redirected to an isolated test database, never the live API.
const browser=await chromium.launch({channel:'msedge',headless:true})
const page=await browser.newPage({viewport:{width:1440,height:1000}})
const errors=[];page.on('pageerror',e=>errors.push(e.message))
await page.route('**/api/**',async route=>{
  const url=new URL(route.request().url())
  const response=await route.fetch({url:'http://127.0.0.1:8011'+url.pathname+url.search,timeout:120000})
  await route.fulfill({response})
})
async function get(path){return page.evaluate(async path=>{const response=await fetch('/api/'+path,{headers:{Authorization:'Bearer '+localStorage.getItem('warehouse_token')}});if(!response.ok)throw Error(await response.text());return response.json()},path)}
async function clear(){page.once('dialog',d=>d.accept());await page.getByRole('button',{name:'ล้างข้อมูลตัวอย่าง',exact:true}).click();await expect(page.getByText('ล้างเฉพาะธุรกรรมตัวอย่างแล้ว รายชื่อสินค้า ลูกค้า รถขนส่ง คนขับ และผังคลังยังอยู่ครบ',{exact:true})).toBeVisible({timeout:120000})}
try{
  await page.goto('http://127.0.0.1:5180/')
  await page.getByLabel('ชื่อผู้ใช้',{exact:true}).fill('admin');await page.getByLabel('รหัสผ่าน',{exact:true}).fill('0000');await page.getByRole('button',{name:'เข้าสู่ระบบ',exact:true}).click()
  await expect(page.getByRole('button',{name:'สร้างแบบเยอะ',exact:true})).toBeVisible()
  await clear()
  const baseline=(await get('inventory/search')).map(r=>r.hu_code).sort()
  await page.getByRole('button',{name:'สร้าง 1 สินค้า Inbound',exact:true}).click()
  await expect(page.locator('.sample-controls-title em')).toContainText('1 HU',{timeout:120000})
  const single=(await get('inventory/search')).filter(r=>!baseline.includes(r.hu_code))
  expect(single).toHaveLength(1);expect(single[0].hu_status).toBe('RECEIVED')
  expect(await get('shipments')).toHaveLength(0)
  expect(await get('delivery-runs')).toHaveLength(0)
  const catalogue=(await get('products')).map(p=>p.id)
  await clear();expect((await get('products')).map(p=>p.id)).toEqual(catalogue)
  await page.getByRole('button',{name:'สร้างแบบเยอะ',exact:true}).click()
  await expect(page.locator('.sample-controls-title em')).toContainText('178 HU',{timeout:120000})
  await page.getByRole('button',{name:'ภาพจำลองสายพาน',exact:true}).click()
  await expect(page.locator('.loading-fleet .scene-truck')).toHaveCount(8)
  await expect(page.locator('.delivery-fleet .scene-truck')).toHaveCount(8)
  expect((await get('inventory/search')).length-baseline.length).toBe(178)
  await page.screenshot({path:'../docs/images/sample-large-desktop.png',fullPage:true})
  await page.setViewportSize({width:390,height:844})
  await expect.poll(()=>page.locator('.pro-sidebar').evaluate(el=>Math.round(el.getBoundingClientRect().right))).toBeLessThanOrEqual(0)
  await expect(page.getByRole('button',{name:'สร้างแบบเยอะ',exact:true})).toBeVisible()
  await expect.poll(()=>page.evaluate(()=>document.documentElement.scrollWidth-window.innerWidth)).toBeLessThanOrEqual(1)
  await page.screenshot({path:'../docs/images/sample-large-mobile.png',fullPage:true})
  await page.screenshot({path:'../docs/images/sample-large-mobile-top.png',fullPage:false})
  await page.setViewportSize({width:1440,height:1000})
  const allCatalogue=(await get('products')).map(p=>p.id)
  await clear()
  expect((await get('products')).map(p=>p.id)).toEqual(allCatalogue)
  expect((await get('inventory/search')).map(r=>r.hu_code).sort()).toEqual(baseline)
  await page.goto('http://127.0.0.1:5180/inbound')
  await expect(page.getByLabel('สินค้า',{exact:true})).toBeEnabled()
  expect(await page.getByLabel('สินค้า',{exact:true}).locator('option').count()).toBeGreaterThan(1)
  expect(errors).toEqual([])
  console.log('PASS: single Inbound only; large 178 HU / 16 trucks; desktop + mobile; clear preserves catalog and unrelated stock; Inbound dropdown populated')
}finally{await browser.close()}
