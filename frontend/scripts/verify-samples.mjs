import {chromium,expect} from '@playwright/test'
const browser=await chromium.launch({channel:'msedge',headless:true})
const page=await browser.newPage({viewport:{width:1440,height:1000}})
const errors=[];page.on('pageerror',e=>errors.push(e.message))
try{
  await page.goto('http://127.0.0.1:5180/')
  await page.getByLabel('ชื่อผู้ใช้',{exact:true}).fill('admin');await page.getByLabel('รหัสผ่าน',{exact:true}).fill('0000');await page.getByRole('button',{name:'เข้าสู่ระบบ',exact:true}).click()
  await expect(page.getByRole('button',{name:'สร้าง Minimal',exact:true})).toBeVisible()
  await page.getByRole('button',{name:'ภาพจำลองสายพาน',exact:true}).click()
  await page.getByRole('button',{name:'สร้าง Minimal',exact:true}).click()
  await expect(page.getByText('สร้าง Minimal เรียบร้อยแล้ว',{exact:true})).toBeVisible()
  await expect(page.locator('.sample-controls-title em')).toContainText('12 HU')
  await expect(page.locator('.loading-fleet .scene-truck')).toHaveCount(1)
  await expect(page.locator('.delivery-fleet .scene-truck')).toHaveCount(1)
  await expect(page.locator('.delivery-fleet .truck-manifest-preview>span')).toHaveCount(2)
  // Direct navigation to each existing zone's actual rack (no warehouse-map detour).
  for(const zone of ['S','M','L','XL','RTN']){
    await expect(page.getByRole('button',{name:`ดูชั้นวางโซน ${zone}`,exact:true})).toBeVisible()
    await page.getByRole('button',{name:`ดูชั้นวางโซน ${zone}`,exact:true}).click()
    await expect(page).toHaveURL(/\/racks\/\d+\/map$/)
    await expect(page.getByRole('heading',{name:'แผนผัง Rack 2D',exact:true})).toBeVisible()
    await expect(page.locator('.rack-scroll .slot.occupied').first()).toBeVisible()
    await page.goto('http://127.0.0.1:5180/dashboard')
  }
  page.once('dialog',dialog=>dialog.accept())
  await page.getByRole('button',{name:'ล้างข้อมูลตัวอย่าง',exact:true}).click()
  await expect(page.getByText('ล้างเฉพาะธุรกรรมตัวอย่างแล้ว รายชื่อสินค้า ลูกค้า รถขนส่ง คนขับ และผังคลังยังอยู่ครบ',{exact:true})).toBeVisible()
  await expect(page.locator('.scene-station.has-cargo')).toHaveCount(0)
  await expect(page.locator('.scene-truck')).toHaveCount(0)
  await page.getByRole('button',{name:'สร้างแบบกลาง',exact:true}).click()
  await expect(page.getByText('สร้างแบบกลาง เรียบร้อยแล้ว',{exact:true})).toBeVisible()
  await expect(page.locator('.sample-controls-title em')).toContainText('46 HU')
  await expect(page.locator('.loading-fleet .scene-truck')).toHaveCount(3)
  await expect(page.locator('.delivery-fleet .scene-truck')).toHaveCount(3)
  await expect(page.locator('.delivery-fleet .truck-manifest-preview>span')).toHaveCount(9)
  await page.getByRole('button',{name:'สร้างแบบกลาง',exact:true}).click()
  await expect(page.getByText('สร้างแบบกลาง เรียบร้อยแล้ว',{exact:true})).toBeVisible()
  await expect(page.locator('.sample-controls-title em')).toContainText('46 HU')
  if(errors.length)throw Error(errors.join('\n'))
  console.log('PASS UI Minimal 12 HU, clear, Medium 46 HU, repeat replaces without duplicates, 6 active trucks, 9 road shipments, all 5 zones open rack directly; no browser errors')
}finally{await browser.close()}
