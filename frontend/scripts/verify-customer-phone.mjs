import {chromium,expect} from '@playwright/test'
const browser=await chromium.launch({channel:'msedge',headless:true})
const page=await browser.newPage({viewport:{width:1280,height:900}})
const errors=[];page.on('pageerror',e=>errors.push(e.message))
await page.route('**/api/**',async route=>{
  const url=new URL(route.request().url())
  const response=await route.fetch({url:'http://127.0.0.1:8011'+url.pathname+url.search})
  await route.fulfill({response})
})
const code='PHONE-UI-'+Date.now(),phone='081-234-5678'
async function get(path){return page.evaluate(async path=>{const r=await fetch('/api/'+path,{headers:{Authorization:'Bearer '+localStorage.getItem('warehouse_token')}});if(!r.ok)throw Error(await r.text());return r.json()},path)}
try{
  await page.goto('http://127.0.0.1:5180/')
  await page.getByLabel('ชื่อผู้ใช้',{exact:true}).fill('admin');await page.getByLabel('รหัสผ่าน',{exact:true}).fill('0000');await page.getByRole('button',{name:'เข้าสู่ระบบ',exact:true}).click()
  await expect(page.getByRole('heading',{name:'ภาพรวมปฏิบัติการ',exact:true})).toBeVisible()
  await page.goto('http://127.0.0.1:5180/master-data')
  await page.locator('article').filter({has:page.getByRole('heading',{name:'Customers',exact:true})}).getByRole('button',{name:'เพิ่มข้อมูล',exact:true}).click()
  const modal=page.locator('.modal')
  await modal.getByLabel('รหัสลูกค้า',{exact:true}).fill(code)
  await modal.getByLabel('ชื่อลูกค้า',{exact:true}).fill('ลูกค้าทดสอบเบอร์โทร')
  await expect(modal.getByLabel('เบอร์โทรลูกค้า',{exact:true})).toHaveAttribute('type','tel')
  await modal.getByLabel('เบอร์โทรลูกค้า',{exact:true}).fill(phone)
  await modal.getByLabel('ที่อยู่จัดส่ง',{exact:true}).fill('99 บ้านทดสอบเบอร์โทร')
  await modal.getByLabel('จังหวัด',{exact:true}).fill('กรุงเทพมหานคร')
  await modal.getByRole('button',{name:'บันทึก',exact:true}).click()
  await expect(modal).toHaveCount(0)
  const customer=(await get('customers')).find(c=>c.customer_code===code)
  expect(customer.phone).toBe(phone)
  await page.goto('http://127.0.0.1:5180/shipments')
  await page.getByRole('button',{name:'สร้าง Shipment',exact:true}).click()
  await page.locator('.modal').getByLabel('ลูกค้า',{exact:true}).selectOption(String(customer.id))
  await page.locator('.modal').getByLabel('จำนวน',{exact:true}).fill('1')
  await page.locator('.modal').getByRole('button',{name:'สร้าง Shipment',exact:true}).click()
  await expect(page.locator('.modal')).toHaveCount(0)
  const shipment=(await get('shipments')).find(s=>s.destination_phone===phone&&s.customer_name===customer.customer_name)
  expect(shipment).toBeTruthy()
  await page.goto('http://127.0.0.1:5180/shipments/'+shipment.id)
  await expect(page.getByLabel('รายละเอียดปลายทางจัดส่ง')).toContainText(phone)
  await expect(page.getByLabel('รายละเอียดปลายทางจัดส่ง')).toContainText('99 บ้านทดสอบเบอร์โทร')
  await expect(page.getByLabel('รถที่จอดรอรับสินค้า',{exact:true})).toHaveCount(0)
  await expect(page.getByRole('button',{name:'สแกนขึ้นรถ',exact:true})).toHaveCount(0)
  expect(errors).toEqual([])
  console.log('PASS customer phone saved from form and shown in shipment destination; shipment has no truck assignment or scan controls')
}finally{await browser.close()}
